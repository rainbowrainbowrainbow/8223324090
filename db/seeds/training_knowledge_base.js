async function seed() {
    const client = await pool.connect();
    try {
        await client.query('BEGIN');

        // Clear existing seed data
        await client.query('DELETE FROM training_test_results');
        await client.query('DELETE FROM training_tests');
        await client.query('DELETE FROM knowledge_base_progress');
        await client.query('DELETE FROM training_badges');
        await client.query('DELETE FROM knowledge_base');

        console.log('Cleared existing data');

        // Insert articles
        const articleMap = {};
        for (let i = 0; i < articles.length; i++) {
            const a = articles[i];
            const result = await client.query(
                `INSERT INTO knowledge_base (title, content, summary, category, role, difficulty, read_time_minutes, icon, sort_order)
                 VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9) RETURNING id`,
                [a.title, a.content, a.summary, a.category, a.role, a.difficulty, a.read_time_minutes, a.icon, i]
            );
            articleMap[a.title] = result.rows[0].id;
            console.log(`  ✅ Article: ${a.title} (id=${result.rows[0].id})`);
        }

        // Insert tests
        for (const t of tests) {
            const articleId = articleMap[t.articleTitle];
            if (!articleId) {
                console.log(`  ⚠️ No article found for test: ${t.title}`);
                continue;
            }
            await client.query(
                `INSERT INTO training_tests (article_id, title, description, questions, passing_score)
                 VALUES ($1, $2, $3, $4, $5)`,
                [articleId, t.title, t.description, JSON.stringify(t.questions), t.passing_score]
            );
            console.log(`  ✅ Test: ${t.title}`);
        }

        await client.query('COMMIT');
        console.log(`\n🎓 Seeded ${articles.length} articles + ${tests.length} tests`);
    } catch (err) {
        await client.query('ROLLBACK');
        console.error('Seed error:', err);
    } finally {
        client.release();
        await pool.end();
    }
}

seed();
